plt.ylabel("Amplitude")
plt.grid()

plt.tight_layout()
plt.show()

"""Frequency Analysis"""

N = len(audio)

X = fft(audio_float)
Y = fft(noisy_audio)

frequencies = fftfreq(N, 1/Fs)

X_magnitude = np.abs(X) / N
Y_magnitude = np.abs(Y) / N

positive = frequencies >= 0

plt.figure(figsize=(14, 6))

plt.plot(frequencies[positive],
         X_magnitude[positive],
         label="Original Audio")

plt.plot(frequencies[positive],
         Y_magnitude[positive],
         label="Noisy Audio",
         alpha=0.7)

plt.xlim(0, 500)
plt.xlabel("Frequency (Hz)")
plt.ylabel("Magnitude")
plt.title("Original vs Noisy Frequency Spectrum")
plt.legend()
plt.grid()
plt.show()

diff = (Y_magnitude - X_magnitude)[positive]
f_pos = frequencies[positive]
print("Detected interference frequency:", f_pos[np.argmax(diff)], "Hz")

