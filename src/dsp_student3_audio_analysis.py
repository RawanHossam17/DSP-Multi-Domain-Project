from scipy.signal import lfilter, freqz
from IPython.display import Audio, display

"""Design the Notch Filter"""

r = 0.995
w0 = 2 * np.pi * f0 / Fs

b = np.array([1, -2*np.cos(w0), 1])
a = np.array([1, -2*r*np.cos(w0), r**2])

print("w0 =", w0)
print("b =", b)
print("a =", a)

"""Zeros, Poles and Stability"""

zeros = np.roots(b)
poles = np.roots(a)

print("Zeros:", zeros)
print("|Zeros| =", np.abs(zeros))
print("Poles:", poles)
print("|Poles| =", np.abs(poles))
print("Stable?", np.all(np.abs(poles) < 1))

filtered_audio = lfilter(b, a, noisy_audio)

"""Filter Frequency Response"""

w, h = freqz(b, a, worN=16384, fs=Fs)

plt.figure(figsize=(12, 4))
plt.plot(w, 20*np.log10(np.abs(h) + 1e-12))
plt.xlim(0, 300)
plt.title("Notch Filter Magnitude Response")
plt.xlabel("Frequency (Hz)")
plt.ylabel("Magnitude (dB)")
plt.grid()
plt.show()

"""Spectrum Comparison"""

Z = fft(filtered_audio)
Z_magnitude = np.abs(Z) / N

plt.figure(figsize=(14, 6))
plt.plot(frequencies[positive], Y_magnitude[positive], label="Noisy", alpha=0.7)
plt.plot(frequencies[positive], Z_magnitude[positive], label="Filtered")
plt.plot(frequencies[positive], X_magnitude[positive], label="Original", alpha=0.5)
plt.xlim(0, 500)
plt.xlabel("Frequency (Hz)")
plt.ylabel("Magnitude")
plt.title("Spectrum: Noisy vs Filtered vs Original")
plt.legend()
plt.grid()
plt.show()

"""Quantitative Evaluation"""

def mag_at(sig, f_target, bw=1):
    S = np.abs(fft(sig)) / len(sig)
    f = fftfreq(len(sig), 1/Fs)
    return S[np.abs(f - f_target) <= bw].max()

before = mag_at(noisy_audio, f0)
after  = mag_at(filtered_audio, f0)
print(f"Magnitude at {f0} Hz: noisy = {before:.1f}, filtered = {after:.2f}")
print(f"Reduction = {20*np.log10(before/after):.1f} dB")

def snr(y):
    return 10*np.log10(np.sum(audio_float**2) / np.sum((y - audio_float)**2))

print(f"SNR noisy    = {snr(noisy_audio):.1f} dB")
print(f"SNR filtered = {snr(filtered_audio):.1f} dB")

